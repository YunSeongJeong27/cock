package com.depositcock.groupbuy;

/**
 * 주문 받는 방법. 공구를 만들 때(주문 링크를 만들기 전) 판매자가 고른다 (2026-10-15 사용자 결정).
 * 댓글만 쓰는 판매자는 주문 링크를 공유하지 않으면 되므로 따로 두지 않는다.
 */
public enum OrderChannel {
    /** 주문 링크만: 닉네임은 선택 입력 (칸은 보임), 댓글 집계는 쓰지 않음 */
    LINK_ONLY,
    /**
     * 주문 링크 + 댓글: 닉네임 필수. 댓글에는 휴대폰 번호가 없어서 링크 주문과 같은 사람인지는 닉네임으로만 비교할 수 있다
     */
    LINK_AND_COMMENT
}
