-- 입금콕 초기 스키마. H2(PostgreSQL 호환 모드)와 PostgreSQL 둘 다에서 동작하도록 작성한다.
-- 2026-10-14: 첫 배포 전에 V1~V6 를 이 파일 하나로 합치고, 고객 테이블을 추가했다 (사용자 승인, docs/design.md "6차").
-- 운영 DB 가 생긴 뒤에는 이미 적용된 이 파일을 고치지 않는다. 변경은 V2__... 새 파일로 추가한다.

CREATE TABLE seller (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                  VARCHAR(255) NOT NULL UNIQUE,
    password_hash          VARCHAR(255) NOT NULL,
    display_name           VARCHAR(100) NOT NULL,
    role                   VARCHAR(20)  NOT NULL,
    plan                   VARCHAR(20)  NOT NULL,
    trial_ends_at          TIMESTAMP    NOT NULL,
    paid_until             DATE,
    suspended              BOOLEAN      NOT NULL DEFAULT FALSE,
    admin_memo             VARCHAR(1000),
    default_bank_name      VARCHAR(50),
    default_account_number VARCHAR(50),
    default_account_holder VARCHAR(50),
    -- 스크린샷(비전 AI) 하루 제한 장수. NULL 이면 설정 기본값(app.vision.daily-capture-limit, 기본 30)
    daily_capture_limit    INTEGER,
    created_at             TIMESTAMP    NOT NULL
);

-- 판매자별 고객. 같은 사람이 다른 판매자에게 주문하면 판매자마다 따로 생긴다 (판매자 사이에 고객 정보를 공유하지 않음).
-- 주문서 고객은 휴대폰 번호로, 댓글로만 주문한 고객은 댓글 닉네임으로 알아본다 (둘 중 하나만 값이 있음).
-- 고객의 휴대폰 번호는 이 테이블에만 둔다. 주문·기기·별칭은 customer_id 로 가리킨다.
CREATE TABLE customer (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id        BIGINT       NOT NULL REFERENCES seller (id) ON DELETE CASCADE,
    -- 정규화한 휴대폰 번호 (숫자만, 예: 01012345678). 댓글 고객은 NULL
    phone            VARCHAR(20),
    -- 댓글 작성자 닉네임. 주문서 고객은 NULL
    comment_nickname VARCHAR(200),
    created_at       TIMESTAMP    NOT NULL,
    CONSTRAINT uq_customer_phone UNIQUE (seller_id, phone),
    CONSTRAINT uq_customer_comment_nickname UNIQUE (seller_id, comment_nickname),
    CONSTRAINT ck_customer_identity CHECK ((phone IS NOT NULL AND comment_nickname IS NULL)
        OR (phone IS NULL AND comment_nickname IS NOT NULL))
);

CREATE TABLE group_buy (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id                  BIGINT       NOT NULL REFERENCES seller (id) ON DELETE CASCADE,
    title                      VARCHAR(200) NOT NULL,
    description                TEXT,
    public_token               VARCHAR(40)  NOT NULL UNIQUE,
    status                     VARCHAR(20)  NOT NULL,
    close_at                   TIMESTAMP,
    bank_name                  VARCHAR(50),
    account_number             VARCHAR(50),
    account_holder             VARCHAR(50),
    pickup_enabled             BOOLEAN      NOT NULL,
    pickup_prepay_enabled      BOOLEAN      NOT NULL,
    pickup_onsite_enabled      BOOLEAN      NOT NULL,
    delivery_enabled           BOOLEAN      NOT NULL,
    shipping_fee_type          VARCHAR(20)  NOT NULL,
    shipping_fee               INTEGER      NOT NULL DEFAULT 0,
    nickname_field_enabled     BOOLEAN      NOT NULL,
    unit_address_field_enabled BOOLEAN      NOT NULL,
    kakao_inquiry_url          VARCHAR(500),
    admin_names                VARCHAR(500),
    created_at                 TIMESTAMP    NOT NULL,
    updated_at                 TIMESTAMP    NOT NULL
);
CREATE INDEX idx_group_buy_seller ON group_buy (seller_id);

CREATE TABLE pickup_point (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_buy_id BIGINT       NOT NULL REFERENCES group_buy (id) ON DELETE CASCADE,
    name         VARCHAR(100) NOT NULL,
    info         VARCHAR(500),
    sort_order   INTEGER      NOT NULL
);

CREATE TABLE product (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_buy_id    BIGINT       NOT NULL REFERENCES group_buy (id) ON DELETE CASCADE,
    name            VARCHAR(200) NOT NULL,
    unit_price      INTEGER      NOT NULL,
    stock_limit     INTEGER,
    sold            INTEGER      NOT NULL DEFAULT 0,
    per_order_limit INTEGER,
    sort_order      INTEGER      NOT NULL,
    version         BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE customer_order (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_buy_id        BIGINT       NOT NULL REFERENCES group_buy (id) ON DELETE CASCADE,
    order_no            INTEGER      NOT NULL,
    source              VARCHAR(20)  NOT NULL,
    -- 주문한 고객 (휴대폰 번호·댓글 닉네임은 customer 테이블에)
    customer_id         BIGINT       NOT NULL REFERENCES customer (id) ON DELETE CASCADE,
    depositor_name      VARCHAR(100),
    -- 주문서에 적은 밴드·카톡 닉네임 (댓글 주문은 댓글 작성자 이름)
    nickname            VARCHAR(200),
    unit_address        VARCHAR(100),
    receive_method      VARCHAR(20)  NOT NULL,
    pickup_point_id     BIGINT REFERENCES pickup_point (id) ON DELETE SET NULL,
    recipient_name      VARCHAR(100),
    -- 배송 받는 분 연락처 (주문한 고객과 다른 사람일 수 있음)
    recipient_phone     VARCHAR(20),
    zipcode             VARCHAR(10),
    address             VARCHAR(300),
    address_detail      VARCHAR(300),
    payment_method      VARCHAR(20)  NOT NULL,
    items_amount        INTEGER      NOT NULL,
    shipping_fee        INTEGER      NOT NULL,
    expected_amount     INTEGER      NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    deposit_reported_at TIMESTAMP,
    -- 입금 확정은 deposit_confirmation 테이블에 기록한다 (주문 테이블에는 두지 않음)
    onsite_paid         BOOLEAN      NOT NULL DEFAULT FALSE,
    picked_up           BOOLEAN      NOT NULL DEFAULT FALSE,
    picked_up_at        TIMESTAMP,
    refund_required     BOOLEAN      NOT NULL DEFAULT FALSE,
    refunded_at         TIMESTAMP,
    lookup_token        VARCHAR(40)  NOT NULL UNIQUE,
    -- 이 주문을 넣은 고객 기기의 쿠키 토큰. 그 기기에만 주문 내용·이전 입력값을 보여준다 (댓글 주문 등은 NULL)
    device_token        VARCHAR(64),
    ordered_at          TIMESTAMP    NOT NULL,
    updated_at          TIMESTAMP    NOT NULL,
    cancelled_at        TIMESTAMP,
    CONSTRAINT uq_order_no UNIQUE (group_buy_id, order_no)
);
CREATE INDEX idx_order_group_buy ON customer_order (group_buy_id);
CREATE INDEX idx_order_customer ON customer_order (group_buy_id, customer_id);
CREATE INDEX idx_order_device ON customer_order (group_buy_id, device_token);

CREATE TABLE order_item (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id              BIGINT       NOT NULL REFERENCES customer_order (id) ON DELETE CASCADE,
    product_id            BIGINT       NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    product_name_snapshot VARCHAR(200) NOT NULL,
    quantity              INTEGER      NOT NULL,
    unit_price_snapshot   INTEGER      NOT NULL
);
CREATE INDEX idx_order_item_order ON order_item (order_id);

-- 쿠키로 고객 기기를 기억한다. 범위는 공구 단위 (개발 전 인터뷰 결과 2번).
-- 기기는 그 기기에서 넣은 주문 + (identified 이면) 본인 확인한 고객의 주문만 본다.
CREATE TABLE customer_device (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_buy_id BIGINT       NOT NULL REFERENCES group_buy (id) ON DELETE CASCADE,
    cookie_token VARCHAR(64)  NOT NULL UNIQUE,
    -- 이 기기의 고객 (마지막으로 주문하거나 본인 확인한 고객)
    customer_id  BIGINT       NOT NULL REFERENCES customer (id) ON DELETE CASCADE,
    -- customer_id 고객으로 본인 확인(입금자명 + 휴대폰)을 거쳤는지. 주문만 넣어서는 TRUE 가 되지 않는다
    identified   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMP    NOT NULL,
    last_seen_at TIMESTAMP    NOT NULL
);

CREATE TABLE deposit_upload (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_buy_id BIGINT      NOT NULL REFERENCES group_buy (id) ON DELETE CASCADE,
    source       VARCHAR(20) NOT NULL,
    file_name    VARCHAR(300),
    uploaded_at  TIMESTAMP   NOT NULL
);

CREATE TABLE deposit_row (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upload_id      BIGINT       NOT NULL REFERENCES deposit_upload (id) ON DELETE CASCADE,
    row_no         INTEGER      NOT NULL,
    depositor_name VARCHAR(200) NOT NULL,
    amount         INTEGER      NOT NULL,
    datetime_text  VARCHAR(100),
    deposited_at   TIMESTAMP
);
CREATE INDEX idx_deposit_row_upload ON deposit_row (upload_id);

-- 입금 확정 기록: 확정 1건 = 1줄. 확정을 취소해도 지우지 않고 cancelled_at 을 채워 이력으로 남긴다.
-- active_* 는 확정이 살아 있는 동안만 값이 있고(취소하면 NULL), 유일 제약으로
-- "주문 1건에 살아 있는 확정 1건", "입금 1건은 주문 1건에만"(정리본 6-2)을 DB 가 지킨다.
-- (부분 유일 인덱스는 H2 가 지원하지 않아서 이 방식을 쓴다. NULL 은 여러 줄이어도 된다)
CREATE TABLE deposit_confirmation (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id              BIGINT       NOT NULL REFERENCES customer_order (id) ON DELETE CASCADE,
    -- 확정에 쓴 입금 줄. 수동 확정이면 NULL. 업로드를 지워 입금 줄이 없어져도 이력은 남긴다 (NULL 로 바뀜)
    deposit_row_id        BIGINT REFERENCES deposit_row (id) ON DELETE SET NULL,
    -- 거래내역 없이 판매자가 직접 확정했는지 (deposit_row_id 가 나중에 NULL 이 돼도 구분되게 따로 둔다)
    manual                BOOLEAN      NOT NULL,
    depositor_name        VARCHAR(200) NOT NULL,
    amount                INTEGER      NOT NULL,
    -- 이 확정이 입금자 별칭을 새로 만들었는지(CREATED)·바꿨는지(CHANGED). 확정 취소 때 이것만 되돌린다
    alias_change          VARCHAR(10),
    -- alias_change 가 CHANGED 일 때 바꾸기 전 고객
    alias_previous_customer_id BIGINT REFERENCES customer (id) ON DELETE SET NULL,
    confirmed_at          TIMESTAMP    NOT NULL,
    cancelled_at          TIMESTAMP,
    active_order_id       BIGINT,
    active_deposit_row_id BIGINT,
    CONSTRAINT uq_confirmation_active_order UNIQUE (active_order_id),
    CONSTRAINT uq_confirmation_active_row UNIQUE (active_deposit_row_id)
);
CREATE INDEX idx_confirmation_order ON deposit_confirmation (order_id);
CREATE INDEX idx_confirmation_row ON deposit_confirmation (deposit_row_id);

CREATE TABLE depositor_alias (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id      BIGINT       NOT NULL REFERENCES seller (id) ON DELETE CASCADE,
    depositor_name VARCHAR(200) NOT NULL,
    customer_id    BIGINT       NOT NULL REFERENCES customer (id) ON DELETE CASCADE,
    created_at     TIMESTAMP    NOT NULL,
    CONSTRAINT uq_alias UNIQUE (seller_id, depositor_name)
);

-- 은행마다 거래내역 열 이름이 달라서, 판매자가 직접 지정한 열 이름을 저장해 둔다.
CREATE TABLE bank_column_preset (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id     BIGINT       NOT NULL REFERENCES seller (id) ON DELETE CASCADE,
    name          VARCHAR(100) NOT NULL,
    date_column   VARCHAR(100),
    name_column   VARCHAR(100) NOT NULL,
    amount_column VARCHAR(100) NOT NULL,
    type_column   VARCHAR(100),
    created_at    TIMESTAMP    NOT NULL,
    CONSTRAINT uq_preset UNIQUE (seller_id, name)
);

-- 2단계: 댓글 스크린샷·텍스트로 받은 댓글
CREATE TABLE imported_comment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_buy_id        BIGINT        NOT NULL REFERENCES group_buy (id) ON DELETE CASCADE,
    source              VARCHAR(20)   NOT NULL,
    seq                 INTEGER       NOT NULL,
    author_name         VARCHAR(200)  NOT NULL,
    content             VARCHAR(2000) NOT NULL,
    duplicate_suspected BOOLEAN       NOT NULL DEFAULT FALSE,
    manual_quantity     INTEGER,
    created_at          TIMESTAMP     NOT NULL
);
CREATE INDEX idx_comment_group_buy ON imported_comment (group_buy_id);

-- 판매자별·날짜별(Asia/Seoul) 비전 AI 로 보낸 캡처 장수 (판매자별 하루 제한)
CREATE TABLE capture_usage (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id   BIGINT  NOT NULL REFERENCES seller (id) ON DELETE CASCADE,
    usage_date  DATE    NOT NULL,
    image_count INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_capture_usage UNIQUE (seller_id, usage_date)
);
